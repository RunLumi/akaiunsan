#!/usr/bin/env node
// Generates migrations/001_initial.cjs from the live test database schema
// (SHOW CREATE TABLE per table). Run manually when the schema changes
// structurally:  node scripts/gen-initial-migration.js
const fs = require('fs');
const path = require('path');
const mysql = require('mysql2/promise');
const config = require('../config/test.json');

(async () => {
  const conn = await mysql.createConnection({
    host: config['db-connection'].host,
    port: config['db-connection'].port || 3306,
    user: config['db-connection'].user,
    password: config['db-connection'].password,
    database: config['db-connection'].database,
  });

  const [tables] = await conn.query('SHOW TABLES');
  const key = Object.keys(tables[0])[0];
  const names = tables.map((t) => t[key]);

  const creates = [];
  for (const name of names) {
    const [[row]] = await conn.query(`SHOW CREATE TABLE \`${name}\``);
    const ddlKey = Object.keys(row).find((k) => k !== 'Table');
    creates.push({ name, ddl: row[ddlKey] });
  }
  await conn.end();

  const out = `// AUTO-GENERATED by scripts/gen-initial-migration.js — do not edit by hand.
// Baseline schema as of generation time. Later schema changes get new
// timestamped migration files instead of edits here.
'use strict';

const tables = ${JSON.stringify(creates, null, 2)};

async function up({ context: sequelize }) {
  await sequelize.query('SET FOREIGN_KEY_CHECKS = 0');
  try {
    for (const { name, ddl } of tables) {
      await sequelize.query(ddl.replace(/CREATE TABLE /, 'CREATE TABLE IF NOT EXISTS '));
    }
  } finally {
    await sequelize.query('SET FOREIGN_KEY_CHECKS = 1');
  }
}

async function down({ context: sequelize }) {
  await sequelize.query('SET FOREIGN_KEY_CHECKS = 0');
  try {
    for (const { name } of tables.reverse()) {
      await sequelize.query(\`DROP TABLE IF EXISTS \\\`\${name}\\\`\`);
    }
  } finally {
    await sequelize.query('SET FOREIGN_KEY_CHECKS = 1');
  }
}

module.exports = { up, down };
`;

  const outPath = path.join(__dirname, '..', 'migrations', '001_initial.cjs');
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, out);
  console.log(`wrote ${outPath} with ${names.length} tables`);
  process.exit(0);
})().catch((e) => {
  console.error(e);
  process.exit(1);
});
